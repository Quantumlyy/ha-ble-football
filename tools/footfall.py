#!/usr/bin/env python3
"""Flash and update the footfall nodes from a laptop.

Only needed if you are not using the ESPHome app inside Home Assistant.
Requires Python 3.10+ and nothing else: ESPHome is installed into .venv on
first use.

    python tools/footfall.py setup            create esphome/secrets.yaml
    python tools/footfall.py flash door-a     first flash, node plugged in via USB
    python tools/footfall.py update           update all nodes over WiFi
    python tools/footfall.py update door-a    update one node over WiFi
    python tools/footfall.py logs door-a      watch a node's log over WiFi
    python tools/footfall.py check            validate all node configs
"""

from __future__ import annotations

import argparse
import base64
import getpass
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys
import venv

ROOT = Path(__file__).resolve().parent.parent
ESPHOME_DIR = ROOT / "esphome"
SECRETS = ESPHOME_DIR / "secrets.yaml"
VENV = ROOT / ".venv"


def nodes() -> list[str]:
    return sorted(p.stem for p in ESPHOME_DIR.glob("*.yaml") if p.name != "secrets.yaml")


def esphome_cmd() -> list[str]:
    """Path to the esphome executable, installing it into .venv if needed."""
    on_path = shutil.which("esphome")
    if on_path:
        return [on_path]
    bindir = VENV / ("Scripts" if os.name == "nt" else "bin")
    exe = bindir / ("esphome.exe" if os.name == "nt" else "esphome")
    if not exe.exists():
        print("Installing ESPHome into .venv (one time, takes a minute)...")
        venv.EnvBuilder(with_pip=True).create(VENV)
        python = bindir / ("python.exe" if os.name == "nt" else "python")
        subprocess.run([str(python), "-m", "pip", "install", "--quiet", "esphome"], check=True)
    return [str(exe)]


def run_esphome(*args: str) -> int:
    return subprocess.run([*esphome_cmd(), *args], cwd=ESPHOME_DIR).returncode


def node_file(name: str) -> str:
    if name not in nodes():
        sys.exit(f"Unknown node '{name}'. Choose one of: {', '.join(nodes())}")
    return f"{name}.yaml"


def require_secrets() -> None:
    if not SECRETS.exists():
        sys.exit("esphome/secrets.yaml is missing. Run: python tools/footfall.py setup")


def yaml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cmd_setup(args: argparse.Namespace) -> int:
    if SECRETS.exists() and not args.force:
        sys.exit(
            "esphome/secrets.yaml already exists. Nodes that are already flashed "
            "depend on it, so it is not overwritten. Use --force to replace it."
        )
    ssid = args.ssid or input("WiFi name (SSID) at the site: ").strip()
    password = args.password or getpass.getpass("WiFi password: ")
    if not ssid or len(password) < 8:
        sys.exit("Need a WiFi name and a password of at least 8 characters.")
    api_key = base64.b64encode(secrets.token_bytes(32)).decode()
    values = {
        "wifi_ssid": ssid,
        "wifi_password": password,
        "api_encryption_key": api_key,
        "ota_password": secrets.token_hex(12),
        "fallback_ap_password": secrets.token_hex(6),
        "footfall_salt": secrets.token_hex(24),
    }
    SECRETS.write_text(
        "# Generated by tools/footfall.py setup. Keep this file: every node and\n"
        "# every later update needs the same values. It is git-ignored.\n"
        + "".join(f"{key}: {yaml_quote(value)}\n" for key, value in values.items()),
        encoding="utf-8",
    )
    print(f"\nWrote {SECRETS.relative_to(ROOT)}")
    print("Home Assistant asks for this encryption key when you add each node:")
    print(f"\n    {api_key}\n")
    print("Next: plug a node in via USB and run: python tools/footfall.py flash door-a")
    return 0


def cmd_flash(args: argparse.Namespace) -> int:
    require_secrets()
    config = node_file(args.node)
    extra = ["--device", args.port] if args.port else []
    print(f"Flashing {args.node} over USB. Pick the serial port if asked.")
    return run_esphome("run", config, *extra)


def cmd_update(args: argparse.Namespace) -> int:
    require_secrets()
    failed = []
    for name in args.nodes or nodes():
        print(f"\n=== Updating {name} over WiFi ===")
        code = run_esphome(
            "run", node_file(name), "--no-logs", "--device", f"footfall-{name}.local"
        )
        if code != 0:
            failed.append(name)
    if failed:
        print(f"\nFailed: {', '.join(failed)}. Is the node powered and on the same network?")
        return 1
    print("\nAll nodes updated.")
    return 0


def cmd_logs(args: argparse.Namespace) -> int:
    require_secrets()
    return run_esphome("logs", node_file(args.node), "--device", f"footfall-{args.node}.local")


def cmd_check(args: argparse.Namespace) -> int:
    require_secrets()
    worst = 0
    for name in nodes():
        worst = max(worst, run_esphome("config", node_file(name)))
    return worst


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("setup", help="create esphome/secrets.yaml")
    p.add_argument("--ssid")
    p.add_argument("--password")
    p.add_argument("--force", action="store_true", help="replace an existing secrets.yaml")
    p.set_defaults(func=cmd_setup)

    p = sub.add_parser("flash", help="first flash of a node over USB")
    p.add_argument("node", help=f"one of: {', '.join(nodes())}")
    p.add_argument("--port", help="serial port, e.g. COM5 or /dev/ttyUSB0")
    p.set_defaults(func=cmd_flash)

    p = sub.add_parser("update", help="update nodes over WiFi")
    p.add_argument("nodes", nargs="*", help="default: all nodes")
    p.set_defaults(func=cmd_update)

    p = sub.add_parser("logs", help="watch a node's log over WiFi")
    p.add_argument("node")
    p.set_defaults(func=cmd_logs)

    p = sub.add_parser("check", help="validate all node configs")
    p.set_defaults(func=cmd_check)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
